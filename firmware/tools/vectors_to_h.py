#!/usr/bin/env python3
"""vectors_to_h.py: generate firmware/swarm_member/test_vectors.h from ledger/test_vectors/vectors.json.

Only PUBLIC TEST KEY material goes into the header (keys k1..k6 are derived from fixed strings and
are published in vectors.json). Never put a real mission key here.

Usage:
    python vectors_to_h.py --vectors <path/to/vectors.json> --out <path/to/test_vectors.h> [--check]
--check exits 1 if --out is missing or stale (does not write).
Stdlib only, ASCII output.
"""
import argparse
import json
import sys
from pathlib import Path

# statements of the board's own test key (k5) that the boot self-test signs and compares
K5_STATEMENTS = ["prevote_block", "prevote_nil", "self_revoke_tamper"]


def strip0x(h):
    return h[2:] if h.startswith("0x") else h


def find_stmt(v, name):
    for s in v["statements"]:
        if s["name"] == name:
            return s
    if v["equivocation"]["a"]["name"] == name:
        return v["equivocation"]["a"]
    if v["equivocation"]["b"]["name"] == name:
        return v["equivocation"]["b"]
    raise KeyError(name)


def stmt_row(s):
    sig = s["sig"]
    return ('  { "%s", %d, %d, %d, %d, "%s",\n'
            '    "%s",\n    "%s",\n    "%s", "%s", %d }' % (
                s["name"], s["msgType"], s["clusterId"], s["height"], s["round"], strip0x(s["subject"]),
                strip0x(s["encoded"]), strip0x(s["digest"]), strip0x(sig["r"]), strip0x(sig["s"]), sig["v"]))


def render(v):
    k5 = next(k for k in v["keys"] if k["name"] == "k5")
    hdr = v["block"]["header"]
    rows = [find_stmt(v, n) for n in K5_STATEMENTS]
    rows += [find_stmt(v, "equiv_a"), find_stmt(v, "equiv_b")]
    for r in rows:
        assert r["signerAddress"] == k5["address"], "statement %s not signed by k5" % r["name"]
    neg = v["negative"]["high_s"]
    L = []
    a = L.append
    a("// test_vectors.h: GENERATED by firmware/tools/vectors_to_h.py from ledger/test_vectors/vectors.json")
    a("// PUBLIC TEST KEYS ONLY (k5 = the board's test identity). Never use for anything real. Do not edit by hand.")
    a("#pragma once")
    a("#include <stdint.h>")
    a("")
    a("struct SsTestStmt {")
    a("  const char* name; uint8_t msgType; uint16_t cluster; uint64_t height; uint32_t round;")
    a("  const char* subject;   // 64 hex")
    a("  const char* encoded;   // 222 hex (111-byte statement)")
    a("  const char* digest;    // 64 hex (sha256 of the statement)")
    a("  const char* r; const char* s; uint8_t v;   // expected RFC6979 low-s signature by k5")
    a("};")
    a("")
    a('static const char SV_MISSION_HEX[]  = "%s";' % strip0x(v["missionId"]))
    a('static const char SV_K5_PRIV_HEX[]  = "%s";' % strip0x(k5["priv"]))
    a('static const char SV_K5_PUB_HEX[]   = "%s";  // 65-byte uncompressed' % strip0x(k5["pub_uncompressed"]))
    a('static const char SV_K5_ADDR[]      = "%s";' % k5["address"])
    a("")
    a("static const SsTestStmt SV_K5_STMTS[] = {")
    a(",\n".join(stmt_row(r) for r in rows))
    a("};")
    a("static const int SV_K5_STMTS_N = %d;" % len(rows))
    a("")
    a("// height-1 block header + expected blockHash (167-byte preimage, spec 10.5)")
    a("struct SsTestHeader { uint16_t cluster; uint64_t height; const char* prevHash; const char* txRoot;")
    a("                      const char* proposer; uint64_t timestampMs; const char* preimage; const char* blockHash; };")
    a("static const SsTestHeader SV_BLOCK = {")
    a('  %d, %d, "%s",\n  "%s",\n  "%s", %d,\n  "%s",\n  "%s" };' % (
        hdr["cluster"], hdr["height"], strip0x(hdr["prevHash"]), strip0x(hdr["txRoot"]),
        strip0x(hdr["proposer"]), hdr["timestampMs"], strip0x(v["block"]["preimage"]), strip0x(v["block"]["blockHash"])))
    a("")
    a("// negative vector: high-s signature (must be rejected by the low-s check)")
    a('static const char SV_HIGHS_R_HEX[] = "%s";' % strip0x(neg["sig"]["r"]))
    a('static const char SV_HIGHS_S_HEX[] = "%s";' % strip0x(neg["sig"]["s"]))
    a("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--vectors", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    v = json.load(open(args.vectors, encoding="utf-8"))
    text = render(v)
    out = Path(args.out)
    if args.check:
        ok = out.exists() and out.read_text(encoding="utf-8") == text
        print("test_vectors.h is UP TO DATE" if ok else "test_vectors.h is STALE or missing")
        return 0 if ok else 1
    out.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s (%d statements)" % (out, len(K5_STATEMENTS) + 2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
